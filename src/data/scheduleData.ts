const STORAGE_KEY = 'congregacion_oeste_preaching_programs_v1';

export function loadStoredPrograms(): Record<string, MonthProgram> {
  if (typeof window === 'undefined') return INITIAL_PROGRAMS;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_PROGRAMS));
      return INITIAL_PROGRAMS;
    }
    const parsed = JSON.parse(raw);
    // Ensure 2026-11 is always seeded if missing
    if (!parsed['2026-11']) {
      parsed['2026-11'] = INITIAL_PROGRAMS['2026-11'];
    }
    return parsed;
  } catch (e) {
    console.error('Error loading stored preaching programs', e);
    return INITIAL_PROGRAMS;
  }
}

export function saveStoredPrograms(programs: Record<string, MonthProgram>) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(programs));
  } catch (e) {
    console.error('Error saving preaching programs', e);
  }
}

export function resetToDefaults(): Record<string, MonthProgram> {
  if (typeof window !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_PROGRAMS));
  }
  return INITIAL_PROGRAMS;
}
